        private void OnEventRoleSelected(GhostRoleInfo role)
        {
            // Player selected a role in the event
            _currentEventButtons?.SetParticipating(true);
            _currentEventButtons?.SetParticipants(1, 1);
            _eventDetailsWindow?.Close();
            _eventDetailsWindow = null;

            // Start countdown and show "Подтвердить готовность"
            _currentEventButtons?.SetReady(true);
        }

        private void OnEventConfirmPressed()
        {
            // Игрок подтвердил готовность
            if (_currentEventButtons != null)
            {
                var currentConfirmed = _currentEventButtons.GetConfirmedCount();
                _currentEventButtons.SetConfirmed(currentConfirmed + 1);
            }
        }

        // Sunrise-Start: автоматическое участие при выборе приоритета
        private void OnEventPriorityChanged()
        {
            // Если игрок выбрал приоритет (не "Никогда"), автоматически участвует
            if (_currentEventButtons != null)
            {
                _currentEventButtons.SetParticipating(true);
                _currentEventButtons.SetParticipants(1, 1);
            }
        }
