        public SunriseGhostRolesWindow()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            MainTabButton.OnPressed += _ =>
            {
                MainTabButton.IsCurrent = true;
                EventsTabButton.IsCurrent = false;
                ChangeView(0);
            };

            EventsTabButton.OnPressed += _ =>
            {
                MainTabButton.IsCurrent = false;
                EventsTabButton.IsCurrent = true;
                ChangeView(1);
            };

            // Sunrise-Start: обновление счетчиков
            UpdateTabCounters();
            // Sunrise-End

            // Initialize events view with example event
            InitializeEventsView();
        }

        private void ChangeView(int view)
        {
            _currentView = view;
            MainView.Visible = view == 0;
            EventsView.Visible = view == 1;
        }

        public void ClearEntries()
        {
            NoRolesMessage.Visible = true;
            EntryContainer.RemoveAllChildren();
            _collapsibleBoxes.Clear();
        }

        public void SaveCollapsibleBoxesStates()
        {
            _uncollapsedStates.Clear();
            foreach (var (key, collapsible) in _collapsibleBoxes)
            {
                if (collapsible.BodyVisible)
                {
                    _uncollapsedStates.Add(key);
                }
            }
        }

        public void RestoreCollapsibleBoxesStates()
        {
            foreach (var (key, collapsible) in _collapsibleBoxes)
            {
                collapsible.BodyVisible = _uncollapsedStates.Contains(key);
            }
        }

        public void AddEntry(string name, string description, string prototypeId, bool hasAccess, FormattedMessage? reason, IEnumerable<GhostRoleInfo> roles, SpriteSystem spriteSystem)
        {
            NoRolesMessage.Visible = false;

            var ghostRoleInfos = roles.ToList();
            var rolesCount = ghostRoleInfos.Count;

            // Sunrise-Start: счетчик обновляется автоматически из GhostSystem
            UpdateTabCounters();
            // Sunrise-End

            var info = new GhostRoleInfoBox(name, description);
            var buttons = new GhostRoleButtonsBox(hasAccess, reason, ghostRoleInfos, spriteSystem);
            buttons.OnRoleSelected += OnRoleRequestButtonClicked;
            buttons.OnRoleRules += OnRoleRulesButtonClicked;
            buttons.OnRoleFollow += OnRoleFollow;

            EntryContainer.AddChild(info);

            if (rolesCount > 1)
            {
                var buttonHeading = new CollapsibleHeading(Loc.GetString("ghost-roles-window-available-button", ("rolesCount", rolesCount)));

                buttonHeading.AddStyleClass(ContainerButton.StyleClassButton);
                buttonHeading.Label.HorizontalAlignment = HAlignment.Center;
                buttonHeading.Label.HorizontalExpand = true;
                buttonHeading.Margin = new Thickness(8, 0, 8, 2);

                var body = new CollapsibleBody
                {
                    Margin = new Thickness(0, 5, 0, 0),
                };

                var collapsible = new Collapsible(buttonHeading, body)
                {
                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    Margin = new Thickness(0, 0, 0, 8),
                };

                body.AddChild(buttons);

                EntryContainer.AddChild(collapsible);
                _collapsibleBoxes.Add(prototypeId, collapsible);
            }
            else
            {
                EntryContainer.AddChild(buttons);
            }
        }

        private void InitializeEventsView()
        {
            // Create example event: Planet Prison
            var eventInfo = new EventInfoBox(
                "Планетарная тюрьма (ID:1)",
                "Планетарная тюрьма - место для отбывания наказания. Вы можете стать сотрудником тюрьмы или заключенным."
            );

            _currentEventButtons = new EventEntryButtons();
            _currentEventButtons.SetParticipants(0, 1);
            _currentEventButtons.OnDetailsButtonPressed += OnEventDetailsPressed;
            _currentEventButtons.OnConfirmButtonPressed += OnEventConfirmPressed;

            var container = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new Thickness(0, 0, 0, 8)
            };

            container.AddChild(eventInfo);
            container.AddChild(_currentEventButtons);
            EventsContainer.AddChild(container);

            // Sunrise-Start: обновление счетчика ивентов
            _eventsCount = 1;
            UpdateTabCounters();
            // Sunrise-End
        }

        // Sunrise-Start: обновление счетчиков в кнопках вкладок
        private void UpdateTabCounters()
        {
            // Парсим число из AvailableGhostRoleCount вместо подсчета вручную
            var rolesCount = _ghostSystem.AvailableGhostRoleCount;
            MainTabButton.LabelText = rolesCount > 0 ? $"Главная ({rolesCount})" : "Главная";
            EventsTabButton.LabelText = _eventsCount > 0 ? $"Ивенты ({_eventsCount})" : "Ивенты";
        }
        // Sunrise-End

